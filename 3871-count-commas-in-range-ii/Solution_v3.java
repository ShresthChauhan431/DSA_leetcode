class Solution {
    public long countCommas(long n) {
        if(n < 1000) return 0; 
        
        if(n < 1000000L) {
            return n - 1000 + 1;
        }
        
        if(n < 1000000000L) return 999000L + 2 * (n - 1000000L + 1);
        
        if(n < 1000000000000L) return 1998999000L + 3 * (n - 1000000000L + 1);
        
        if(n < 1000000000000000L) return 2998998999000L + 4 * (n - 1000000000000L + 1);
        
        if(n < 1000000000000000000L) return 3998998998999000L + 5 * (n - 1000000000000000L + 1);
        
        return 4998998998998999000L + 6 * (n - 1000000000000000000L + 1); 
    }
}